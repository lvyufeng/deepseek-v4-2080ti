#!/usr/bin/env python3
"""Benchmark exact Qwen prefix reuse with one persistent TP request loop.

The root process owns a long-lived QwenEngine. Each subsequent request extends
its previous prompt with the tokens generated by the previous request and a
new deterministic suffix, which models a single conversation growing over time.
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
import time
from pathlib import Path
from typing import Any


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ckpt", required=True)
    parser.add_argument("--token-ids-file", required=True)
    parser.add_argument("--binary", default="build/cpp_engine/pocketllm_engine")
    parser.add_argument("--tp-world", type=int, default=4)
    parser.add_argument("--devices", default="0,1,2,3")
    parser.add_argument("--max-context", type=int, required=True)
    parser.add_argument("--max-new-tokens", type=int, default=4)
    parser.add_argument("--layers", type=int, default=0)
    parser.add_argument("--prefill-chunk-tokens", type=int, default=512)
    parser.add_argument("--kv-cache-dtype", choices=("fp16", "fp8"), default="fp16")
    parser.add_argument(
        "--qwen-mtp-tokens", type=int, default=0,
        help="enable native Qwen MTP with this many speculative draft tokens",
    )
    parser.add_argument(
        "--qwen-mtp-adaptive", action="store_true",
        help="start at K=1 and adapt up to --qwen-mtp-tokens",
    )
    parser.add_argument(
        "--qwen-dspark",
        help="enable external Qwen DSpark from this checkpoint directory",
    )
    parser.add_argument("--nccl-id-path", default=".tmp/qwen_prefix_cache/nccl.id")
    parser.add_argument("--log-dir", default=".tmp/qwen_prefix_cache/logs")
    parser.add_argument("--suffix-tokens", type=int, default=512)
    parser.add_argument(
        "--compression-prefix-tokens", type=int, default=0,
        help="after append rounds, retain this many leading tokens and replace the rest",
    )
    parser.add_argument(
        "--compression-suffix-tokens", type=int, default=512,
        help="new deterministic suffix size for the compressed request",
    )
    parser.add_argument(
        "--disable-prefix-cache", action="store_true",
        help="force cold prefill for every request; use for parity A/B",
    )
    return parser.parse_args()


def read_tokens(path: Path) -> list[int]:
    tokens = [int(item) for item in path.read_text(encoding="ascii").split(",") if item]
    if not tokens:
        raise RuntimeError(f"token fixture is empty: {path}")
    return tokens


def parse_result(line: str) -> dict[str, Any] | None:
    if not line.startswith("qwen_persistent_result=1 "):
        return None
    result: dict[str, Any] = {}
    for key, value in re.findall(r"(\w+)=([^\s]+)", line):
        if key == "tokens":
            result[key] = [int(item) for item in value.split(",") if item]
            continue
        try:
            result[key] = int(value)
        except ValueError:
            try:
                result[key] = float(value)
            except ValueError:
                result[key] = value
    return result


def parse_worker_tokens(path: Path) -> list[list[int]]:
    results: list[list[int]] = []
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if not line.startswith("qwen_persistent_worker_result=1 "):
            continue
        match = re.search(r"\btokens=([^\s]*)", line)
        if match is None:
            raise RuntimeError(f"worker result is missing tokens: {path}")
        results.append([int(item) for item in match.group(1).split(",") if item])
    return results


def wait_result(root: subprocess.Popen[str]) -> dict[str, Any]:
    while True:
        line = root.stdout.readline() if root.stdout is not None else ""
        if not line:
            raise RuntimeError("persistent Qwen root exited before returning a result")
        parsed = parse_result(line.strip())
        if parsed is not None:
            return parsed


def main() -> int:
    args = parse_args()
    binary = Path(args.binary).resolve()
    ckpt = Path(args.ckpt).resolve()
    token_file = Path(args.token_ids_file).resolve()
    if not binary.is_file():
        raise SystemExit(f"binary not found: {binary}")
    if not ckpt.is_dir():
        raise SystemExit(f"checkpoint not found: {ckpt}")
    base = read_tokens(token_file)
    devices = [int(item) for item in args.devices.split(",") if item.strip()]
    if len(devices) != args.tp_world:
        raise SystemExit("--devices count must match --tp-world")
    if args.max_new_tokens <= 0 or args.suffix_tokens <= 0:
        raise SystemExit("max-new-tokens and suffix-tokens must be positive")
    if args.qwen_mtp_tokens < 0:
        raise SystemExit("--qwen-mtp-tokens must be non-negative")
    if args.qwen_mtp_tokens > 0 and args.layers != 0:
        raise SystemExit("native MTP validation requires --layers 0")
    if args.qwen_dspark and args.qwen_mtp_tokens > 0:
        raise SystemExit("--qwen-dspark and native MTP are mutually exclusive")
    dspark = Path(args.qwen_dspark).resolve() if args.qwen_dspark else None
    if dspark is not None and (
        args.layers != 0
        or not (dspark / "config.json").is_file()
        or not (dspark / "model.safetensors").is_file()
    ):
        raise SystemExit("DSpark requires --layers 0 and a complete checkpoint")

    id_path = Path(args.nccl_id_path).resolve()
    id_path.parent.mkdir(parents=True, exist_ok=True)
    for path in (id_path, Path(str(id_path) + ".qwen")):
        try:
            path.unlink()
        except FileNotFoundError:
            pass
    log_dir = Path(args.log_dir).resolve()
    log_dir.mkdir(parents=True, exist_ok=True)
    worker_logs = []
    workers: list[subprocess.Popen[bytes]] = []
    root: subprocess.Popen[str] | None = None
    started = time.monotonic()
    try:
        commands = []
        for rank in range(args.tp_world):
            commands.append([
                str(binary),
                "--ckpt", str(ckpt),
                "--tp-world", str(args.tp_world),
                "--tp-rank", str(rank),
                "--device", "0",
                "--nccl-id-path", str(id_path),
                "--max-context", str(args.max_context),
                "--prefill-chunk-tokens", str(args.prefill_chunk_tokens),
                "--kv-cache-dtype", args.kv_cache_dtype,
                "--smoke-layers", str(args.layers),
                "--qwen-persistent-stdin",
            ])
            if args.disable_prefix_cache:
                commands[-1].append("--qwen-no-prefix-cache")
            if args.qwen_mtp_tokens > 0:
                commands[-1] += ["--qwen-mtp-tokens", str(args.qwen_mtp_tokens)]
                if args.qwen_mtp_adaptive:
                    commands[-1].append("--qwen-mtp-adaptive")
            if dspark is not None:
                commands[-1] += ["--qwen-dspark", str(dspark)]
        for rank in range(1, args.tp_world):
            log_path = log_dir / f"rank{rank}.log"
            log = log_path.open("wb")
            worker_logs.append(log)
            env = os.environ.copy()
            env["CUDA_VISIBLE_DEVICES"] = str(devices[rank])
            workers.append(subprocess.Popen(commands[rank], stdout=log, stderr=subprocess.STDOUT, env=env))
        env = os.environ.copy()
        env["CUDA_VISIBLE_DEVICES"] = str(devices[0])
        root = subprocess.Popen(
            commands[0], stdin=subprocess.PIPE, stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT, text=True, bufsize=1, env=env,
        )
        # First request uses the base fixture. Later requests include the
        # previous assistant output and a deterministic new suffix.
        prompt = list(base)
        root_tokens: list[list[int]] = []
        requests = 3
        if args.compression_prefix_tokens > 0:
            requests += 1
        for request_index in range(requests):
            if request_index == 3 and args.compression_prefix_tokens > 0:
                if args.compression_prefix_tokens >= len(prompt):
                    raise RuntimeError("compression prefix must be shorter than current prompt")
                prompt = prompt[:args.compression_prefix_tokens]
                prompt.extend(
                    50000 + request_index * 1000 + index
                    for index in range(args.compression_suffix_tokens)
                )
            if prompt and len(prompt) + args.max_new_tokens > args.max_context:
                raise RuntimeError("request prompt plus generation exceeds max-context")
            line = f"{args.max_new_tokens} " + " ".join(str(token) for token in prompt) + "\n"
            assert root.stdin is not None
            root.stdin.write(line)
            root.stdin.flush()
            result = wait_result(root)
            print(
                f"request={request_index} prompt_tokens={result.get('prompt_tokens')} "
                f"wall={result.get('wall')} "
                f"prefill_tps={result.get('prefill_tokens_per_s')} "
                f"decode_tps={result.get('decode_tokens_per_s')} "
                f"computed_tps={result.get('prefill_computed_tokens_per_s')} "
                f"reused={result.get('prefix_reused_tokens')} "
                f"computed={result.get('prefix_computed_tokens')} "
                f"matched={result.get('prefix_matched_tokens')} "
                f"source={result.get('prefix_resume_source')} "
                f"snapshots={result.get('prefix_snapshots')} "
                f"snapshot_bytes={result.get('prefix_snapshot_bytes')} "
                f"mtp_accept_rate={result.get('mtp_accept_rate')} "
                f"tokens={result.get('tokens')}"
            )
            generated = result.get("tokens")
            if not isinstance(generated, list) or not generated:
                raise RuntimeError(f"invalid generated token list: {result}")
            root_tokens.append([int(token) for token in generated])
            # The engine has already executed all but the final generated token
            # into its recurrent/KV state. Including the complete assistant
            # output therefore exercises live reuse for the next request and
            # computes only the final token plus the new suffix.
            prompt = prompt + [int(token) for token in generated]
            prompt.extend((request_index + 1) % 32000 + index for index in range(args.suffix_tokens))
        if root.stdin is not None:
            root.stdin.close()
        root.wait(timeout=120)
        for worker in workers:
            worker.wait(timeout=120)
        if root.returncode != 0 or any(worker.returncode != 0 for worker in workers):
            raise RuntimeError(
                f"persistent processes failed root={root.returncode} "
                f"workers={[worker.returncode for worker in workers]}"
            )
        if dspark is not None:
            for rank in range(1, args.tp_world):
                worker_tokens = parse_worker_tokens(log_dir / f"rank{rank}.log")
                if worker_tokens != root_tokens:
                    raise RuntimeError(
                        f"DSpark TP-rank token parity failed for rank {rank}"
                    )
            print("dspark_rank_token_parity=PASS")
        print(f"elapsed_wall_seconds={time.monotonic() - started:.3f}")
        return 0
    finally:
        if root is not None and root.poll() is None:
            root.terminate()
        for worker in workers:
            if worker.poll() is None:
                worker.terminate()
        for handle in worker_logs:
            handle.close()


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except subprocess.TimeoutExpired as exc:
        print(f"timeout: {exc}", file=sys.stderr)
        raise SystemExit(1)
